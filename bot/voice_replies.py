"""Выбор случайной голосовой реплики для ответа на голосовую команду.

Тексты самих реплик хранит `bot.voice_reply_phrases` — этот модуль знает
только, как из набора фраз одного действия выбрать одну на конкретный
случай, не повторяя предыдущий выбор подряд. Разделение осознанное: тексты
могут расти и правиться отдельно от логики выбора, и наоборот.
"""

from __future__ import annotations

import random

from bot.voice_reply_phrases import PHRASES

# Последняя выбранная фраза по каждому действию — чтобы не повторить её же
# на следующий раз (см. докстринг `pick_reply`). Не потокобезопасно, но это
# не требуется: голосовые команды разбираются и исполняются в одном цикле
# событий asyncio (`bot.cogs.music.execute_voice_command`), конкурентного
# доступа из разных ОС-потоков к этому состоянию нет.
_last_choice: dict[str, str] = {}


def pick_reply(action: str) -> str | None:
    """Возвращает случайную фразу для действия `action`, либо `None`, если фраз для него нет.

    Отсутствие фраз для действия — не ошибка, а часть контракта: например у
    `repeat` отдельного ответа нет, бот и так произносит запрошенный текст,
    и лишняя реплика перед ним была бы только помехой.

    Выбранная в прошлый раз для ЭТОГО ЖЕ действия фраза не повторяется — на
    коротких списках (10-15 вариантов) повтор подряд звучит как заезженная
    пластинка. Если у действия ровно одна фраза, повторение неизбежно и не
    считается сбоем: выбирать не из чего, но ответ всё равно должен быть.
    """
    phrases = PHRASES.get(action)
    if not phrases:
        return None
    previous = _last_choice.get(action)
    candidates = [phrase for phrase in phrases if phrase != previous]
    choice = random.choice(candidates) if candidates else random.choice(phrases)
    _last_choice[action] = choice
    return choice
