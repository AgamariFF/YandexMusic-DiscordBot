"""Доменные ошибки модуля nekto.me (наследники общего `BotError` бота)."""

from __future__ import annotations

from bot.errors import BotError


class NektoConnectError(BotError):
    """Не удалось установить или удержать соединение с сервисом nekto.me."""

    default_message = "Не удалось подключиться к чат-рулетке."


class NektoBannedError(BotError):
    """Аккаунт, привязанный к токену, заблокирован сервисом nekto.me."""

    default_message = "Аккаунт заблокирован сервисом чат-рулетки."


class NektoProtocolError(BotError):
    """Сервис nekto.me вернул сообщение об ошибке протокола либо неожиданный ответ."""

    default_message = "Сервис чат-рулетки вернул ошибку."


class NektoStateError(BotError):
    """Операция вызвана в состоянии сессии, которое её не допускает.

    Например, повторный запуск поиска собеседника во время уже идущего
    разговора — это ошибка использования API, а не сетевая или
    протокольная проблема, поэтому в этом случае на сервер вообще ничего
    не отправляется.
    """

    default_message = "Недопустимая операция для текущего состояния чат-рулетки."
